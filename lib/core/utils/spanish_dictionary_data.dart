/// Palabras terminadas en 'cion' o 'sion' que en español siempre llevan tilde en la 'ó'.
String? checkCommonSuffixRule(String lowerWord) {
  if (lowerWord.length > 4 &&
      lowerWord.endsWith('cion') &&
      !lowerWord.endsWith('ción')) {
    return '${lowerWord.substring(0, lowerWord.length - 4)}ción';
  }
  if (lowerWord.length > 4 &&
      lowerWord.endsWith('sion') &&
      !lowerWord.endsWith('sión')) {
    return '${lowerWord.substring(0, lowerWord.length - 4)}sión';
  }
  return null;
}
